$basePath = "S:\我的云端硬盘\Apps\Linux\3X-UI\3x-ui\web\translation"

$keys = @(
    "subAutoUpdateDesc",
    "subCronExpr",
    "subCronFormatHint",
    "subKeepUpdated",
    "subScheduledUpdate",
    "subUpdateXray",
    "subXrayUpdates"
)

foreach ($lang in $translations.Keys) {
    $file = Join-Path $basePath "$lang.json"
    Write-Host "Processing $file"

    $lines = Get-Content $file -Encoding UTF8
    $t = $translations[$lang]

    # Find the last line that is just "}" (the root object closing)
    $lastBraceIndex = -1
    for ($i = $lines.Count - 1; $i -ge 0; $i--) {
        if ($lines[$i].TrimEnd() -eq "}") {
            $lastBraceIndex = $i
            break
        }
    }

    if ($lastBraceIndex -eq -1) {
        Write-Host "ERROR: Could not find closing brace in $file"
        continue
    }

    # Find the line just before the last brace (should be "  }" closing tgbot)
    # Add a comma to it since it will no longer be the last property
    $prevIndex = $lastBraceIndex - 1
    if ($prevIndex -ge 0 -and $lines[$prevIndex].TrimEnd() -eq "  }") {
        $lines[$prevIndex] = "  },"
    }

    # Build the new key lines with 2-space indentation
    $newLines = @()
    foreach ($key in $keys) {
        $val = $t[$key]
        # Escape backslashes and double quotes for JSON
        $val = $val -replace '\\', '\\' -replace '"', '\"'
        $newLines += "  `"$key`": `"$val`","
    }

    # Insert before the last brace
    $result = $lines[0..($lastBraceIndex - 1)] + $newLines + $lines[$lastBraceIndex..($lines.Count - 1)]

    # Write back with UTF8 (no BOM)
    $result | Out-File -FilePath $file -Encoding utf8

    Write-Host "  Done: added $($newLines.Count) keys"
}

Write-Host "All files processed."
